#!/usr/bin/env python3
"""Bake the memory card banner (96x32) and icon (32x32) for the settings save: engine/platform/gamecube/card_art.h

Original art in the retail palette (ViewportBG 55 43 29, ClassMenuLight 175 127 1): a gold star badge and a banner with
the game name. Both are CI8 (256 colour, RGB5A3 palette) in GX's 8x4 texel tiling, the layout the IPL card manager reads.
Needs Pillow; the output is committed, so building the game does not.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

BG = (55, 43, 29)
GOLD = (175, 127, 1)
LIGHT = (255, 176, 0)
WHITE = (255, 255, 255)


def star(cx, cy, r_out, r_in):
	import math
	pts = []
	for i in range(10):
		r = r_out if i % 2 == 0 else r_in
		a = -math.pi / 2 + i * math.pi / 5
		pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
	return pts


def banner():
	im = Image.new("RGB", (96, 32), BG)
	d = ImageDraw.Draw(im)
	d.rectangle((0, 0, 95, 31), outline=GOLD)
	d.rectangle((2, 2, 93, 29), outline=(110, 80, 4))
	try:
		f1 = ImageFont.truetype("/usr/share/fonts/truetype/noto/NotoSans-Bold.ttf", 11)
		f2 = ImageFont.truetype("/usr/share/fonts/truetype/noto/NotoSans-Regular.ttf", 9)
	except OSError:
		f1 = f2 = ImageFont.load_default()
	d.text((7, 4), "DAY OF DEFEAT", font=f1, fill=LIGHT)
	d.text((8, 18), "Name and settings", font=f2, fill=WHITE)
	return im


def icon():
	im = Image.new("RGB", (32, 32), BG)
	d = ImageDraw.Draw(im)
	d.ellipse((1, 1, 30, 30), fill=(110, 80, 4), outline=GOLD)
	d.ellipse((4, 4, 27, 27), fill=BG, outline=GOLD)
	d.polygon(star(16, 16.5, 10, 4.2), fill=LIGHT, outline=GOLD)
	return im


def ci8(im):
	p = im.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
	pal = p.getpalette()[:768]
	pal += [0] * (768 - len(pal))
	tlut = []
	for i in range(256):
		r, g, b = pal[i * 3:i * 3 + 3]
		tlut.append(0x8000 | ((r >> 3) << 10) | ((g >> 3) << 5) | (b >> 3))  # RGB5A3, opaque
	w, h = p.size
	px = p.load()
	pixels = []
	for ty in range(0, h, 4):
		for tx in range(0, w, 8):
			for y in range(4):
				for x in range(8):
					pixels.append(px[tx + x, ty + y])
	return pixels, tlut


def emit(name, values, per_line):
	lines = []
	for i in range(0, len(values), per_line):
		lines.append("\t" + ", ".join(str(v) if name.endswith("pixels") else "0x%04X" % v for v in values[i:i + per_line]) + ",")
	return "\n".join(lines)


def main():
	out = sys.argv[1] if len(sys.argv) > 1 else "engine/platform/gamecube/card_art.h"
	bp, bt = ci8(banner())
	ip, it = ci8(icon())
	with open(out, "w") as f:
		f.write("/* generated by scripts/bake-card-art.py - do not edit */\n#pragma once\n\n")
		f.write("static const unsigned char gc_card_banner_pixels[%d] = {\n%s\n};\n" % (len(bp), emit("pixels", bp, 24)))
		f.write("static const unsigned short gc_card_banner_tlut[256] = {\n%s\n};\n" % emit("tlut", bt, 8))
		f.write("static const unsigned char gc_card_icon_pixels[%d] = {\n%s\n};\n" % (len(ip), emit("pixels", ip, 24)))
		f.write("static const unsigned short gc_card_icon_tlut[256] = {\n%s\n};\n" % emit("tlut", it, 8))
	banner().resize((384, 128), Image.NEAREST).save("/tmp/osk-work-build/card_banner.png")
	icon().resize((128, 128), Image.NEAREST).save("/tmp/osk-work-build/card_icon.png")
	print("wrote", out)


if __name__ == "__main__":
	main()
